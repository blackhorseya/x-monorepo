-- Products: what one SKU sells for. The price is minor units plus its own
-- ISO 4217 currency (each product has one); the checks keep the domain's
-- invariants true for a row nobody wrote through the aggregate: whatever the
-- database accepts, GetProduct / ListProducts can rebuild.
--
-- sku is COLLATE "C": keyset paging (sku > ?), ORDER BY sku and LIKE 'prefix%' compare bytes,
-- as the memory repository and Go do, whatever locale the cluster was initialised with. A
-- C-collation primary key also serves the LIKE prefix, so there is no extra pattern_ops index.
CREATE TABLE catalog.products (
    sku            text COLLATE "C" PRIMARY KEY CHECK (octet_length(sku) BETWEEN 1 AND 64),
    -- not blank = at least one character that strings.TrimSpace would keep. It trims
    -- tab, LF, VT, FF, CR, space, U+0085, U+00A0 and the Unicode Z categories (U+1680,
    -- U+2000-200A, U+2028, U+2029, U+202F, U+205F, U+3000). Spelled out, not [[:space:]],
    -- which follows the locale.
    name           text        NOT NULL CHECK (
        name ~ '[^\t\n\v\f\r \u0085\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000]'
        AND char_length(name) <= 200),
    price_amount   bigint      NOT NULL CHECK (price_amount >= 0),
    price_currency char(3)     NOT NULL REFERENCES catalog.currencies (code),
    active         boolean     NOT NULL,
    -- optimistic lock: Save updates only WHERE version matches, then bumps it
    version        bigint      NOT NULL DEFAULT 0,
    updated_at     timestamptz NOT NULL
);
