#!/usr/bin/env python3
"""Regenerates the ISO 4217 code list of the catalog from SIX's List One.

  curl -fsSLo list-one.xml https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml
  python3 -I currency_gen.py list-one.xml go  > currency_codes.go
  python3 -I currency_gen.py list-one.xml sql   # the VALUES rows of a migration's seed

Migrations are immutable once released: a new publication means a new migration
that inserts/deletes the difference, and this file regenerated to match
(currency_test.go and the Postgres tests fail while the two disagree).
"""
import sys
import xml.etree.ElementTree as ET

path, mode = sys.argv[1], sys.argv[2]
root = ET.parse(path).getroot()
published = root.get("Pblshd")
codes = sorted({e.text.strip() for e in root.iter("Ccy") if e.text and e.text.strip()})

if mode == "sql":
    print(",\n".join(f"    ('{c}')" for c in codes))
elif mode == "go":
    print("// Code generated by currency_gen.py from SIX List One; DO NOT EDIT.")
    print("// Source: https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml")
    print(f"// Published: {published} ({len(codes)} codes)")
    print()
    print("package product\n")
    print("var currencyCodes = []string{")
    for c in codes:
        print(f'\t"{c}",')
    print("}")
else:
    sys.exit("mode must be go or sql")
